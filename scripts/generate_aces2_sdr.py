"""Regenerate the Vulkan ACES 2 SDR transform with OpenColorIO 2.5.2."""

import argparse
from pathlib import Path
import re

import PyOpenColorIO as ocio


CONFIG = "cg-config-v4.0.0_aces-v2.0_ocio-v2.5"
DISPLAY = "sRGB - Display"
VIEW = "ACES 2.0 - SDR 100 nits (Rec.709)"
SOURCE = "Linear Rec.709 (sRGB)"
ROWS = 363


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"Unexpected generated shader expression: {old}")
    return text.replace(old, new)


def generate():
    if ocio.__version__ != "2.5.2":
        raise ValueError("Use OpenColorIO 2.5.2.")
    config = ocio.Config.CreateFromBuiltinConfig(CONFIG)
    display = ocio.DisplayViewTransform(src=SOURCE, display=DISPLAY, view=VIEW)
    transforms = list(config.getProcessor(display).createGroupTransform())
    encoding = transforms[-1]
    if (not isinstance(encoding, ocio.ExponentWithLinearTransform)
        or encoding.getGamma() != [2.4, 2.4, 2.4, 1.0]
        or encoding.getDirection() != ocio.TRANSFORM_DIR_INVERSE):
        raise ValueError("Unexpected display encoding.")

    linear = ocio.GroupTransform(transforms=transforms[:-1])
    processor = ocio.Config.CreateRaw().getProcessor(linear).getDefaultGPUProcessor()
    desc = ocio.GpuShaderDesc.CreateShaderDesc()
    desc.setLanguage(ocio.GPU_LANGUAGE_HLSL_DX11)
    desc.setFunctionName("poima_aces2_transform")
    desc.setResourcePrefix("aces2_")
    processor.extractGpuShaderInfo(desc)
    reach, cusp = list(desc.getTextures())
    for texture, expected in ((reach, "aces2_reach_m_table_0"), (cusp, "aces2_gamut_cusp_table_0")):
        if (texture.textureName, texture.width, texture.height, texture.interpolation) != (
            expected, ROWS, 1, ocio.INTERP_NEAREST
        ):
            raise ValueError("Unexpected ACES 2 lookup layout.")
    if list(desc.get3DTextures()):
        raise ValueError("Unexpected ACES 2 3D lookup.")
    shader = desc.getShaderText()
    match = re.search(r"static const float aces2_gamut_cusp_table_0_hues_array\[363\] = \{([^}]+)\};\n", shader)
    if not match:
        raise ValueError("Missing ACES 2 hue lookup.")
    hues = [float(value) for value in match[1].split(",")]
    if len(hues) != ROWS:
        raise ValueError("Unexpected ACES 2 hue count.")
    shader = replace_once(shader, match[0], "")
    shader = replace_once(shader, """Texture1D aces2_reach_m_table_0;
SamplerState aces2_reach_m_table_0Sampler;
Texture1D aces2_gamut_cusp_table_0;
SamplerState aces2_gamut_cusp_table_0Sampler;""", """cbuffer Aces2Lookup : register(b2) {
    float4 aces2_cusp_hue[363];
    float4 aces2_reach[363];
};""")
    for old, new in (
        ("aces2_reach_m_table_0.Sample(aces2_reach_m_table_0Sampler, (i_lo + 0.5) / float (363)).r",
         "aces2_reach[int(i_lo)].x"),
        ("aces2_reach_m_table_0.Sample(aces2_reach_m_table_0Sampler, (i_hi + 0.5) / float (363)).r",
         "aces2_reach[int(i_hi)].x"),
        ("aces2_gamut_cusp_table_0.Sample(aces2_gamut_cusp_table_0Sampler, (float(i_hi) - 1.0 + 0.5) / float(363)).rgb",
         "aces2_cusp_hue[i_hi - 1].xyz"),
        ("aces2_gamut_cusp_table_0.Sample(aces2_gamut_cusp_table_0Sampler, (float(i_hi) + 0.5) / float(363)).rgb",
         "aces2_cusp_hue[i_hi].xyz"),
    ):
        shader = replace_once(shader, old, new)
    shader, count = re.subn(r"aces2_gamut_cusp_table_0_hues_array\[([^\]]+)\]", r"aces2_cusp_hue[\1].w", shader)
    if count != 4:
        raise ValueError("Unexpected hue lookup references.")

    notice = ("// SPDX-License-Identifier: BSD-3-Clause\n"
              "// Copyright Contributors to the OpenColorIO Project.\n"
              "// Generated by scripts/generate_aces2_sdr.py. See THIRD_PARTY_NOTICES.md.\n")
    shader = "\n".join(line.rstrip() for line in shader.strip().splitlines())
    shader = notice + "\n" + shader + "\n"
    cusp_rows = cusp.getValues().reshape((ROWS, 3))
    packed = [(*row, hue) for row, hue in zip(cusp_rows, hues, strict=True)]
    packed += [(value, 0, 0, 0) for value in reach.getValues()]

    def decimal(value):
        token = format(float(value), ".9g")
        if "." not in token and "e" not in token:
            token += ".0"
        return token + "f"

    table = notice + "\n#pragma once\n#include <array>\n\nnamespace poima::render_scene_output {\n"
    table += f"inline constexpr std::array<std::array<float,4>,{2 * ROWS}> aces2_lookup{{{{\n"
    table += "\n".join("    {" + ", ".join(map(decimal, row)) + "}," for row in packed)
    table += "\n}};\n}\n"
    return shader, table


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    shader, table = generate()
    (args.root / "shaders/aces2_sdr.hlsli").write_text(shader, encoding="utf-8")
    (args.root / "src/aces2_sdr_lookup.hpp").write_text(table, encoding="utf-8")


if __name__ == "__main__":
    main()
